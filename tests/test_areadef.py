class TestParseShapes(unittest.TestCase):
    def test_skips_malformed_and_coerces_unknown_kind(self):
        raw = [
            {"id": 1, "kind": "rect", "bbox": [0, 0, 10, 10]},
            {"id": 2, "kind": "weird", "bbox": [0, 0, 10, 10]},   # unknown kind -> rect
            {"id": 3, "kind": "rect", "bbox": [0, 0, 10]},        # bad bbox len -> skip
            "not a dict",                                          # skip
            {"id": 4, "kind": "rect", "bbox": [0, 0, float("inf"), 10]},  # non-finite -> skip
        ]
        shapes, skipped, coerced = areaDef._parse_shapes(raw)
        self.assertEqual(len(shapes), 2)
        self.assertEqual(skipped, 3)   # bad-len, non-dict, non-finite
        self.assertEqual(coerced, 1)   # unknown kind -> rect

    def test_hostile_numbers_are_skipped_not_raised(self):
        # Both of these come straight out of json.loads (it accepts Infinity and
        # unbounded int literals) and both raise OverflowError, not
        # TypeError/ValueError: int(float("inf")) and float(10**400).
        raw = json.loads("""[
            {"id": Infinity, "kind": "rect", "bbox": [0, 0, 10, 10]},
            {"id": 2, "page": Infinity, "kind": "rect", "bbox": [0, 0, 10, 10]},
            {"id": 3, "kind": "rect", "bbox": [0, 0, 1%s, 10]},
            {"id": 4, "kind": "rect", "bbox": [0, 0, 10, 10], "chamfer": Infinity}
        ]""" % ("0" * 400))
        shapes, skipped, _coerced = areaDef._parse_shapes(raw)
        self.assertEqual(skipped, 1)                       # only the huge bbox
        self.assertEqual(len(shapes), 3)
        by_name = {s.name: s for s in shapes}
        self.assertEqual(by_name["area_0"].sid, 5)         # bad id -> 0 -> reassigned
        self.assertEqual(by_name["area_2"].page, 0)        # bad page -> 0
        self.assertEqual(by_name["area_4"].chamfer, 0.0)   # non-finite -> 0.0

    def test_null_name_falls_back_to_default(self):
        raw = [{"id": 5, "kind": "rect", "bbox": [0, 0, 10, 10], "name": None}]
        shapes, _, _ = areaDef._parse_shapes(raw)
        self.assertEqual(shapes[0].name, "area_5")   # not the literal "None"
        self.assertTrue(all(s.kind in areaDef.VALID_KINDS for s in shapes))

    def test_control_characters_are_stripped_from_names(self):
        raw = [{"id": 1, "kind": "rect", "bbox": [0, 0, 10, 10],
                "name": "in\x00voice\r\n no\x07 1"}]
        shapes, _, _ = areaDef._parse_shapes(raw)
        # Printable characters (including the spaces) survive; the rest go.
        self.assertEqual(shapes[0].name, "invoice no 1")

    def test_printable_unicode_names_are_left_alone(self):
        raw = [{"id": 1, "kind": "rect", "bbox": [0, 0, 10, 10], "name": "ümläut 文書"}]
        shapes, _, _ = areaDef._parse_shapes(raw)
        self.assertEqual(shapes[0].name, "ümläut 文書")


