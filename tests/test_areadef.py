class TestGeometryHelpers(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.win = areaDef.AnnotatorWindow(theme="dark")

    def test_mean(self):
        self.assertEqual(areaDef._mean([1, 2, 3]), 2.0)
        self.assertEqual(areaDef._mean([]), 0.0)

    def test_apply_snapped_bbox_keeps_an_edge_clamped_circle_square(self):
        # A snap that pushes a circle past the right edge translates it back in
        # at full size; clamping the edges independently made it an ellipse
        # whose exported radius no longer matched its bbox.
        s = Shape(1, "circle", "c", 700, 100, 800, 200)
        self.assertTrue(areaDef.apply_snapped_bbox(s, (760, 100, 860, 200), 800, 600))
        x1, y1, x2, y2 = s.bbox()
        self.assertAlmostEqual(x2 - x1, y2 - y1)
        self.assertEqual((x2, y2), (800.0, 200.0))

    def test_apply_snapped_bbox_shrinks_a_circle_larger_than_the_canvas(self):
        s = Shape(1, "circle", "c", 0, 0, 10, 10)
        self.assertTrue(areaDef.apply_snapped_bbox(s, (0, 0, 900, 900), 800, 600))
        x1, y1, x2, y2 = s.bbox()
        self.assertEqual((x2 - x1, y2 - y1), (600.0, 600.0))

    def test_dedupe_shape_ids_is_idempotent_and_page_aware(self):
        shapes = [Shape(1, "rect", "a", 0, 0, 10, 10, page=0),
                  Shape(1, "rect", "b", 0, 0, 10, 10, page=1),
                  Shape(1, "rect", "c", 0, 0, 10, 10, page=1)]
        areaDef._dedupe_shape_ids(shapes)
        self.assertEqual([(s.page, s.sid) for s in shapes], [(0, 1), (1, 1), (1, 2)])
        areaDef._dedupe_shape_ids(shapes)   # re-runnable after a page move
        self.assertEqual([(s.page, s.sid) for s in shapes], [(0, 1), (1, 1), (1, 2)])

    def test_chamfer_polygon_has_eight_points(self):
        poly = self.win.canvas._make_chamfer_polygon(0, 0, 100, 60, 10)
        self.assertEqual(len(poly), 8)

    def test_chamfer_polygon_clamps_oversized_chamfer(self):
        # chamfer 999 on a 10x10 box clamps to 5 -> all points within the box
        poly = self.win.canvas._make_chamfer_polygon(0, 0, 10, 10, 999)
        for p in poly:
            self.assertGreaterEqual(p.x(), 0)
            self.assertLessEqual(p.x(), 10)
            self.assertGreaterEqual(p.y(), 0)
            self.assertLessEqual(p.y(), 10)

    def test_cluster_shapes_groups_by_key(self):
        shapes = [
            Shape(1, "rect", "a", 0, 0, 10, 10),
            Shape(2, "rect", "b", 1, 50, 11, 60),   # close left edge -> same cluster
            Shape(3, "rect", "c", 200, 0, 210, 10),  # far left edge -> new cluster
        ]
        clusters = areaDef._running_mean_clusters(shapes, key=lambda s: s.bbox()[0], tol=5.0)
        self.assertEqual(len(clusters), 2)
        self.assertEqual(len(clusters[0]), 2)


