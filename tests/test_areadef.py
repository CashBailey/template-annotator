class TestDetectionDedup(unittest.TestCase):
    def test_dedupe_prefers_decoded_over_overlapping_blank(self):
        dets = [
            {"bbox": (10, 10, 50, 50), "kind": "qr", "payload": ""},
            {"bbox": (11, 11, 49, 49), "kind": "qr", "payload": "HELLO"},
            {"bbox": (200, 200, 240, 240), "kind": "qr", "payload": "X"},
        ]
        out = areaDef._dedupe_detections(dets, iou_thresh=0.3)
        self.assertEqual(len(out), 2)
        near = [d for d in out if d["bbox"][0] < 100]
        self.assertEqual(len(near), 1)
        self.assertEqual(near[0]["payload"], "HELLO")

    def test_dedupe_keeps_the_first_of_two_decoded_overlaps(self):
        # Backends run in a fixed order and both may decode the same code. The
        # rule is first-wins UNLESS the winner is blank, so a later backend can
        # never overwrite an already-decoded payload (only fill in an empty one).
        dets = [
            {"bbox": (10, 10, 50, 50), "kind": "qr", "payload": "FIRST"},
            {"bbox": (11, 11, 49, 49), "kind": "qr", "payload": "SECOND"},
        ]
        out = areaDef._dedupe_detections(dets, iou_thresh=0.3)
        self.assertEqual([d["payload"] for d in out], ["FIRST"])
        self.assertEqual(out[0]["bbox"], (10, 10, 50, 50))   # and its geometry


@unittest.skipUnless(HAS_CV2, "needs OpenCV for marker fixtures + detection")
class TestMarkerDetection(unittest.TestCase):
    def _qr_image(self, text="HELLO123", scale=8, border=40):
        import cv2
        import numpy as np
        from PIL import Image
        enc = cv2.QRCodeEncoder.create()
        qr = enc.encode(text)
        qr = cv2.resize(qr, None, fx=scale, fy=scale, interpolation=cv2.INTER_NEAREST)
        h, w = qr.shape[:2]
        canvas = np.full((h + 2 * border, w + 2 * border), 255, np.uint8)
        canvas[border:border + h, border:border + w] = qr
        return Image.fromarray(canvas, "L").convert("RGB")

    def _apriltag_image(self, tag_id=7, size=160, border=60):
        import cv2
        import numpy as np
        from PIL import Image
        d = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_APRILTAG_36h11)
        marker = cv2.aruco.generateImageMarker(d, tag_id, size)
        h, w = marker.shape[:2]
        canvas = np.full((h + 2 * border, w + 2 * border), 255, np.uint8)
        canvas[border:border + h, border:border + w] = marker
        return Image.fromarray(canvas, "L").convert("RGB")

    def test_detects_qr_and_decodes_payload(self):
        dets = areaDef.detect_markers(self._qr_image("HELLO123"))
        self.assertTrue(any(d["payload"] == "HELLO123" for d in dets),
                        f"QR payload not decoded: {dets}")

    def test_detects_apriltag_marker(self):
        dets = areaDef.detect_markers(self._apriltag_image(tag_id=7))
        self.assertTrue(dets, "AprilTag/ArUco marker not detected")
        x1, y1, x2, y2 = dets[0]["bbox"]
        self.assertGreater(x2 - x1, 80)   # roughly the marker's size

    def test_apriltag_large_image_downscales_and_scales_back(self):
        # Audit fix: pupil_apriltags segfaults on big frames; _markers_apriltag
        # caps the input size then scales corners back to full resolution. This
        # 1800px image exceeds APRILTAG_MAX_DIM, so it exercises that path.
        import cv2
        import numpy as np
        d = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_APRILTAG_36h11)
        marker = cv2.aruco.generateImageMarker(d, 5, 400)
        canvas = np.full((1800, 1800), 255, np.uint8)
        canvas[700:1100, 700:1100] = marker
        dets = areaDef._markers_apriltag(np.ascontiguousarray(canvas))
        self.assertTrue(dets, "apriltag not detected on a large (downscaled) image")
        x1, y1, x2, y2 = dets[0]["bbox"]
        self.assertAlmostEqual(x1, 700, delta=50)   # corners back at full-res coords
        self.assertAlmostEqual(x2, 1100, delta=50)

    def test_none_and_blank(self):
        from PIL import Image
        self.assertEqual(areaDef.detect_markers(None), [])
        self.assertEqual(areaDef.detect_markers(Image.new("RGB", (80, 80), "white")), [])


