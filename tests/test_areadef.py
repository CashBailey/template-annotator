class TestNormalizeRollback(unittest.TestCase):
    def test_chamfer_normalize_preserves_vertical_coords(self):
        # Three chamfers in one column with uneven heights and gaps. The original
        # normalizeZones aligns columns horizontally and NEVER moves y0/y1; the
        # vertical height/gap evening that crept in must be gone.
        shapes = [
            Shape(1, "chamfer", "a", 100, 10, 300, 40, chamfer=5),
            Shape(2, "chamfer", "b", 100, 100, 300, 130, chamfer=5),
            Shape(3, "chamfer", "c", 100, 200, 300, 280, chamfer=5),
        ]
        original_y = [(s.y1, s.y2) for s in shapes]
        areaDef.normalize_chamfer_columns(shapes, 1000, 1000)
        for s, (oy1, oy2) in zip(shapes, original_y):
            _x1, y1, _x2, y2 = s.bbox()
            self.assertAlmostEqual(y1, oy1, places=3, msg=f"shape {s.sid} top moved")
            self.assertAlmostEqual(y2, oy2, places=3, msg=f"shape {s.sid} bottom moved")

    def test_chamfer_normalize_still_aligns_left_edges(self):
        # Horizontal column alignment must still happen (left edges converge).
        shapes = [
            Shape(1, "chamfer", "a", 100, 10, 300, 40, chamfer=5),
            Shape(2, "chamfer", "b", 108, 100, 308, 130, chamfer=5),
        ]
        areaDef.normalize_chamfer_columns(shapes, 1000, 1000)
        self.assertAlmostEqual(shapes[0].bbox()[0], shapes[1].bbox()[0], places=3)


