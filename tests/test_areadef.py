class TestPdfDimensions(unittest.TestCase):
    @unittest.skipUnless(HAS_FITZ, "needs PyMuPDF")
    def test_load_media_dimensions_uses_render_scale(self):
        # Point size * PDF_RENDER_SCALE must equal what _load_media_dimensions returns,
        # so normalize-json --image-size-source matches GUI-authored coordinates.
        import fitz
        doc = fitz.open(str(SAMPLE_PDF))
        rect = doc.load_page(0).rect
        doc.close()
        w, h = areaDef._load_media_dimensions(str(SAMPLE_PDF))
        self.assertEqual(w, round(rect.width * areaDef.PDF_RENDER_SCALE))
        self.assertEqual(h, round(rect.height * areaDef.PDF_RENDER_SCALE))

    @unittest.skipUnless(HAS_FITZ, "needs PyMuPDF")
    def test_normalize_with_pdf_override_matches_json_dims(self):
        # Regression: overriding dims from the PDF must actually take effect, not just
        # not-crash. _normalize_json_payload clusters rects into columns using a left-edge
        # gap tolerance of 0.02 *relative to image width*, so the same absolute 14px gap
        # clusters (and gets normalized) at the real PDF width (800: 14/800=0.0175 < 0.02)
        # but not at the payload's own stale declared width (400: 14/400=0.035 > 0.02).
        # That makes "changed" and the resulting bbox genuinely depend on which width is
        # used -- unlike two identical-bbox shapes, whose reconstructed bbox is
        # algebraically invariant to whatever w is passed in (division by w to get a
        # fraction, then multiplication by the same w to get back pixels, cancels).
        payload = {
            "image": {"width": 400, "height": 300},
            "shapes": [
                {"id": 1, "kind": "rect", "bbox": [100, 10, 300, 50], "page": 0},
                {"id": 2, "kind": "rect", "bbox": [114, 100, 300, 140], "page": 0},
            ],
        }

        # No override: falls back to the payload's own (stale) 400x300 -> gap too wide
        # relative to that width -> no clustering -> shapes untouched.
        out_json_dims, changed_json = areaDef._normalize_json_payload(payload, None, None)
        self.assertEqual(changed_json, 0)
        self.assertEqual(out_json_dims["shapes"][0]["bbox"], [100, 10, 300, 50])

        # Correct override: the PDF's real rendered size -> gap within tolerance ->
        # both shapes normalize into a shared column at the mean left edge (107).
        w, h = areaDef._load_media_dimensions(str(SAMPLE_PDF))
        self.assertEqual((w, h), (800, 600))
        out_override, changed_override = areaDef._normalize_json_payload(payload, w, h)
        self.assertEqual(changed_override, 2)
        self.assertAlmostEqual(out_override["shapes"][0]["bbox"][0], 107.0, places=3)
        self.assertNotEqual(out_override["shapes"][0]["bbox"], out_json_dims["shapes"][0]["bbox"])

        # A wrong override must NOT reproduce the correct result: a w/h swap and a
        # grossly mis-scaled override both land back on "no clustering" (unchanged bbox),
        # proving the assertions above aren't satisfied by an ignored/broken override.
        out_swapped, changed_swapped = areaDef._normalize_json_payload(payload, h, w)
        self.assertEqual(changed_swapped, 0)
        self.assertEqual(out_swapped["shapes"][0]["bbox"], [100, 10, 300, 50])

