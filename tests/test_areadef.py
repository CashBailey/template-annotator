class TestAtomicWrite(unittest.TestCase):
    def test_writes_content(self):
        d = tempfile.mkdtemp()
        path = os.path.join(d, "out.json")
        areaDef._atomic_write_text(path, '{"ok": true}')
        self.assertEqual(json.loads(Path(path).read_text()), {"ok": True})

    def test_preserves_original_on_failure(self):
        d = tempfile.mkdtemp()
        path = os.path.join(d, "out.txt")
        Path(path).write_text("ORIGINAL")
        # Passing a non-serializable type forces failure before replace.
        with self.assertRaises(Exception):
            areaDef._atomic_write_text(path, object())  # type: ignore[arg-type]
        self.assertEqual(Path(path).read_text(), "ORIGINAL")
        # No stray temp files left behind.
        self.assertEqual([p for p in os.listdir(d) if p.endswith(".tmp")], [])

    def test_keeps_the_target_file_mode(self):
        # mkstemp() makes 0600 files and os.replace carries the mode over, so a
        # group-readable project used to become owner-only on every save.
        d = tempfile.mkdtemp()
        path = os.path.join(d, "out.json")
        Path(path).write_text("{}")
        os.chmod(path, 0o644)
        areaDef._atomic_write_text(path, '{"ok": true}')
        self.assertEqual(os.stat(path).st_mode & 0o777, 0o644)

    def test_new_file_follows_the_umask(self):
        d = tempfile.mkdtemp()
        path = os.path.join(d, "fresh.json")
        old = os.umask(0o022)
        try:
            areaDef._atomic_write_text(path, "{}")
        finally:
            os.umask(old)
        self.assertEqual(os.stat(path).st_mode & 0o777, 0o644)

    def test_ensure_suffix(self):
        self.assertEqual(areaDef._ensure_suffix("a", ".json"), "a.json")
        self.assertEqual(areaDef._ensure_suffix("a.json", ".json"), "a.json")
        self.assertEqual(areaDef._ensure_suffix("a.csv", ".json"), "a.csv")
        # A bare trailing dot is not a real extension.
        self.assertEqual(areaDef._ensure_suffix("a.", ".json"), "a.json")


