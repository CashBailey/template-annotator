class TestProject(unittest.TestCase):
    def _proj(self):
        return areaDef.Project(image_path="/tmp/x.png", width=1000, height=1000)

    def test_add_get_rename_move_delete(self):
        p = self._proj()
        s = p.add_shape("rect", "Field", (10, 10, 40, 30))
        self.assertEqual(s.sid, 1)
        self.assertEqual(p.get(1).name, "Field")
        self.assertTrue(p.rename(1, "Renamed"))
        self.assertEqual(p.get(1).name, "Renamed")
        self.assertTrue(p.move(1, 5, -5))
        self.assertEqual(p.get(1).bbox(), (15.0, 5.0, 45.0, 25.0))
        self.assertTrue(p.set_bbox(1, (0, 0, 100, 50)))
        self.assertEqual(p.get(1).bbox(), (0.0, 0.0, 100.0, 50.0))
        self.assertTrue(p.delete(1))
        self.assertEqual(len(p.shapes), 0)

    def test_next_sid_increments(self):
        p = self._proj()
        p.add_shape("rect", "a", (0, 0, 10, 10))
        p.add_shape("circle", "b", (0, 0, 10, 10))
        self.assertEqual([s.sid for s in p.shapes], [1, 2])

    def test_invalid_kind_raises(self):
        with self.assertRaises(ValueError):
            self._proj().add_shape("triangle", "x", (0, 0, 10, 10))

    def test_json_round_trip(self):
        p = self._proj()
        p.add_shape("rect", "A", (10, 20, 110, 60), page=2)
        with tempfile.TemporaryDirectory() as d:
            path = os.path.join(d, "proj.json")
            p.write(path)
            p2 = areaDef.Project.from_json(path)
            self.assertEqual(p2.width, 1000)
            self.assertEqual(len(p2.shapes), 1)
            self.assertEqual(p2.get(1).name, "A")
            self.assertEqual(p2.get(1).page, 2)

    def test_add_boxes_dedups(self):
        p = self._proj()
        p.add_shape("rect", "existing", (0, 0, 100, 100))
        added = p.add_boxes([(10, 10, 40, 40), (500, 500, 540, 540)], "checkbox")
        self.assertEqual(added, 1)   # the (10,10,..) center is inside the existing shape

    def test_normalize_all_kinds(self):
        p = self._proj()
        p.add_shape("rect", "a", (100, 10, 300, 50))
        p.add_shape("rect", "b", (108, 100, 300, 140))   # ~same column
        counts = p.normalize()
        self.assertEqual(counts["rect"], 2)
        self.assertAlmostEqual(p.shapes[0].bbox()[0], p.shapes[1].bbox()[0], places=3)

    def test_snap_to_lines(self):
        p = self._proj()
        p.add_shape("rect", "f", (50, 50, 200, 106))
        h_lines = [(100.0, 0.0, 500.0)]
        n = p.snap_to_lines(h_lines, [], tol=12.0)
        self.assertEqual(n, 1)
        self.assertAlmostEqual(p.get(1).bbox()[3], 100.0)  # bottom snapped

    def test_snap_to_lines_only_touches_the_detected_page(self):
        # Lines detected on ONE page of a PDF must not drag shapes that live on
        # another page (they are different bitmaps in the same coordinate space).
        p = self._proj()
        on_p0 = p.add_shape("rect", "p0", (50, 50, 200, 106), page=0)
        on_p1 = p.add_shape("rect", "p1", (50, 50, 200, 106), page=1)
        n = p.snap_to_lines([(100.0, 0.0, 500.0)], [], tol=12.0, page=1)
        self.assertEqual(n, 1)
        self.assertAlmostEqual(on_p1.bbox()[3], 100.0)                    # snapped
        self.assertEqual(on_p0.bbox(), (50.0, 50.0, 200.0, 106.0))        # untouched

    def test_snap_to_lines_without_page_snaps_everything(self):
        # Default (no page given) keeps the historical single-page behaviour.
        p = self._proj()
        p.add_shape("rect", "p0", (50, 50, 200, 106), page=0)
        p.add_shape("rect", "p1", (50, 50, 200, 106), page=1)
        self.assertEqual(p.snap_to_lines([(100.0, 0.0, 500.0)], [], tol=12.0), 2)


