class TestNormalizeJsonPayload(unittest.TestCase):
    def test_aligns_left_edges_in_a_column(self):
        payload = {
            "image": {"width": 1000, "height": 1000},
            "shapes": [
                {"id": 1, "kind": "rect", "bbox": [100, 10, 300, 50]},
                {"id": 2, "kind": "rect", "bbox": [110, 100, 300, 140]},  # ~same column
            ],
        }
        out, changed = areaDef._normalize_json_payload(payload, None, None)
        self.assertEqual(changed, 2)
        left1 = out["shapes"][0]["bbox"][0]
        left2 = out["shapes"][1]["bbox"][0]
        self.assertAlmostEqual(left1, left2, places=3)

    def test_non_rect_shapes_untouched(self):
        payload = {
            "image": {"width": 1000, "height": 1000},
            "shapes": [
                {"id": 1, "kind": "circle", "bbox": [100, 10, 140, 50]},
                {"id": 2, "kind": "circle", "bbox": [110, 100, 150, 140]},
            ],
        }
        out, changed = areaDef._normalize_json_payload(payload, None, None)
        self.assertEqual(changed, 0)
        self.assertEqual(out["shapes"][0]["bbox"], [100, 10, 140, 50])

    def test_missing_dimensions_raises(self):
        with self.assertRaises(ValueError):
            areaDef._normalize_json_payload({"shapes": []}, None, None)


