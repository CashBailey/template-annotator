class TestLineDetection(unittest.TestCase):
    def _image_with_lines(self, w=200, h=200, hy=100, vx=50):
        from PIL import Image, ImageDraw
        img = Image.new("RGB", (w, h), "white")
        d = ImageDraw.Draw(img)
        d.line([(20, hy), (180, hy)], fill="black", width=2)   # horizontal rule
        d.line([(vx, 10), (vx, 190)], fill="black", width=2)   # vertical rule
        return img

    def test_detects_horizontal_and_vertical(self):
        img = self._image_with_lines(hy=100, vx=50)
        h_lines, v_lines = areaDef.detect_document_lines(img)
        self.assertTrue(any(abs(y - 100) <= 2 for (y, _a, _b, *_) in h_lines),
                        f"no h-line near y=100 in {h_lines}")
        self.assertTrue(any(abs(x - 50) <= 2 for (x, _a, _b, *_) in v_lines),
                        f"no v-line near x=50 in {v_lines}")

    def test_thick_rule_reports_half_thickness(self):
        # A line carries its perpendicular half-thickness as a 4th element so
        # fields can snap to its outer edge instead of its centre.
        from PIL import Image, ImageDraw
        img = Image.new("RGB", (200, 200), "white")
        ImageDraw.Draw(img).line([(20, 100), (180, 100)], fill="black", width=5)
        h_lines, _ = areaDef.detect_document_lines(img)
        near = [L for L in h_lines if abs(L[0] - 100) <= 4]
        self.assertTrue(near, f"thick rule near y=100 missing from {h_lines}")
        self.assertGreaterEqual(len(near[0]), 4)   # tuple carries thickness
        self.assertGreater(near[0][3], 1.0)        # ~2px half-thickness for a 5px rule

    def test_empty_image_returns_no_lines(self):
        from PIL import Image
        h, v = areaDef.detect_document_lines(Image.new("RGB", (50, 50), "white"))
        self.assertEqual(h, [])
        self.assertEqual(v, [])

    def test_none_image(self):
        self.assertEqual(areaDef.detect_document_lines(None), ([], []))

    def _text_page(self):
        from PIL import Image, ImageDraw
        img = Image.new("RGB", (600, 400), "white")
        d = ImageDraw.Draw(img)
        for row in range(6):
            d.text((40, 30 + row * 22),
                   "The quick brown fox jumps over the lazy dog ABCDEFGHIJK",
                   fill="black")
        d.text((40, 200), "FOR COMPANY USE ONLY", fill="black")  # heading-ish
        return img

    def test_text_is_not_detected_as_lines(self):
        # The regression this guards: rows/blocks of text must NOT register as
        # rules. Allow at most a tiny number of spurious lines, none crossing
        # the dense-text band (y < 260).
        h_lines, _ = areaDef.detect_document_lines(self._text_page())
        in_text = [L for L in h_lines if L[0] < 260]
        self.assertEqual(in_text, [], f"text mistaken for lines: {in_text}")

    def test_real_rule_survives_alongside_text(self):
        from PIL import ImageDraw
        img = self._text_page()
        ImageDraw.Draw(img).line([(40, 320), (560, 320)], fill="black", width=2)
        h_lines, _ = areaDef.detect_document_lines(img)
        self.assertTrue(any(abs(L[0] - 320) <= 2 for L in h_lines),
                        f"real rule at y=320 missing from {h_lines}")
        # and still nothing in the text band
        self.assertFalse(any(L[0] < 260 for L in h_lines))

    def test_sparse_bridged_run_rejected_by_fill(self):
        # A long but mostly-empty dashed pattern (low fill) is not a rule.
        from PIL import Image, ImageDraw
        img = Image.new("RGB", (600, 200), "white")
        d = ImageDraw.Draw(img)
        for x in range(20, 560, 30):       # 3px dashes every 30px -> ~10% fill
            d.line([(x, 100), (x + 3, 100)], fill="black", width=2)
        h_lines, _ = areaDef.detect_document_lines(img)
        self.assertFalse(any(abs(L[0] - 100) <= 2 for L in h_lines),
                         "sparse dashed pattern wrongly detected as a rule")

    def test_thick_filled_bar_not_a_thin_line(self):
        # A tall filled rectangle is a block, not a thin rule.
        from PIL import Image, ImageDraw
        img = Image.new("RGB", (600, 300), "white")
        ImageDraw.Draw(img).rectangle([60, 120, 540, 160], fill="black")  # 40px tall
        h_lines, _ = areaDef.detect_document_lines(img, max_thickness=6)
        self.assertFalse(any(125 <= L[0] <= 155 for L in h_lines),
                         "filled block interior wrongly detected as a thin line")

    def test_detects_short_vertical_rule(self):
        # A short vertical rule (~31px) — e.g. a pill-box side or a stub margin
        # rule — was dropped by the old 40px vertical length floor.
        from PIL import Image, ImageDraw
        img = Image.new("RGB", (200, 200), "white")
        ImageDraw.Draw(img).line([(60, 80), (60, 110)], fill="black", width=2)
        _h, v_lines = areaDef.detect_document_lines(img)
        self.assertTrue(any(abs(x - 60) <= 2 for (x, *_r) in v_lines),
                        f"short vertical near x=60 missing from {v_lines}")

    def test_bridges_broken_vertical_rule(self):
        # A vertical rule split by a ~5px break (a rounded-corner gap or dashed
        # margin rule). Each half (13px) is below the floor, so it is only found
        # when the gap is bridged into one run — needs the wider vertical gap.
        from PIL import Image, ImageDraw
        img = Image.new("RGB", (200, 200), "white")
        d = ImageDraw.Draw(img)
        d.line([(100, 40), (100, 52)], fill="black", width=3)   # 13px
        d.line([(100, 58), (100, 70)], fill="black", width=3)   # 13px, 5px gap above
        _h, v_lines = areaDef.detect_document_lines(img)
        self.assertTrue(any(abs(x - 100) <= 3 for (x, *_r) in v_lines),
                        f"broken vertical near x=100 missing from {v_lines}")


