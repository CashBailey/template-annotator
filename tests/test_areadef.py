class TestShape(unittest.TestCase):
    def test_bbox_normalizes_swapped_coords(self):
        s = Shape(1, "rect", "x", 100, 200, 40, 60)
        self.assertEqual(s.bbox(), (40, 60, 100, 200))

    def test_bbox_already_ordered(self):
        s = Shape(1, "rect", "x", 5, 5, 25, 35)
        self.assertEqual(s.bbox(), (5, 5, 25, 35))

    def test_export_rect(self):
        d = Shape(7, "rect", "Name", 10, 20, 30, 40).as_export_dict()
        self.assertEqual(d["id"], 7)
        self.assertEqual(d["kind"], "rect")
        self.assertEqual(d["bbox"], [10.0, 20.0, 30.0, 40.0])
        self.assertNotIn("center", d)
        self.assertNotIn("chamfer", d)

    def test_export_circle_has_center_and_radius(self):
        d = Shape(1, "circle", "o", 0, 0, 10, 10).as_export_dict()
        self.assertEqual(d["center"], [5.0, 5.0])
        self.assertEqual(d["radius"], 5.0)

    def test_export_chamfer_is_clamped_to_box(self):
        # A 10x10 box can hold at most a chamfer of 5. An over-large value must
        # not leak into exported JSON as an invalid geometry.
        d = Shape(1, "chamfer", "c", 0, 0, 10, 10, chamfer=999).as_export_dict()
        self.assertLessEqual(d["chamfer"], 5.0)

    def test_clone_is_independent(self):
        s = Shape(1, "rect", "a", 0, 0, 1, 1)
        c = s.clone()
        c.x1 = 99
        c.name = "b"
        self.assertEqual(s.x1, 0)
        self.assertEqual(s.name, "a")


class TestUndoManager(unittest.TestCase):
    def _state(self, n):
        return AppState(shapes=[Shape(i, "rect", str(i), 0, 0, 1, 1) for i in range(n)])

    def test_undo_then_redo_roundtrip(self):
        um = UndoManager()
        um.save_state(self._state(1))         # snapshot has 1 shape
        current = self._state(2)              # we now have 2 shapes
        restored = um.undo(current)
        self.assertEqual(len(restored.shapes), 1)
        redone = um.redo(self._state(1))
        self.assertEqual(len(redone.shapes), 2)

    def test_undo_empty_returns_none(self):
        self.assertIsNone(UndoManager().undo(self._state(0)))

    def test_save_clears_redo(self):
        um = UndoManager()
        um.save_state(self._state(1))
        um.undo(self._state(2))               # populates redo
        um.save_state(self._state(3))         # should clear redo
        self.assertEqual(um.redo_stack, [])

    def test_history_is_capped(self):
        um = UndoManager(max_history=3)
        for i in range(10):
            um.save_state(self._state(i))
        self.assertLessEqual(len(um.undo_stack), 3)


