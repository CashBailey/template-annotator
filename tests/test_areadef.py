class TestLazyBackendImports(unittest.TestCase):
    """The CV backends (cv2/numpy/pyzbar/pupil_apriltags) cost ~200 ms to import.
    They must load on the first detection call, never at `import areaDef`, so
    pure-JSON CLI work doesn't pay for a feature it never uses. Holds whether or
    not the backends are installed."""

    # Runs the JSON-only `list-shapes` command in-process, then checks what the
    # interpreter actually loaded.
    PROBE = (
        "import sys\n"
        "sys.argv = ['areaDef.py', 'list-shapes', {path!r}]\n"
        "import areaDef\n"
        "assert 'cv2' not in sys.modules, 'importing areaDef pulled cv2'\n"
        "try:\n"
        "    areaDef.main()\n"
        "except SystemExit as exc:\n"
        "    assert not exc.code, 'list-shapes failed: %r' % (exc.code,)\n"
        "for name in ('cv2', 'pyzbar', 'pupil_apriltags'):\n"
        "    assert name not in sys.modules, name + ' was imported by a pure-JSON CLI run'\n"
        "print('CLEAN')\n"
    )

    def test_json_cli_path_never_imports_the_cv_backends(self):
        with tempfile.TemporaryDirectory() as d:
            proj = os.path.join(d, "proj.json")
            p = areaDef.Project("/tmp/x.png", 100, 100)
            p.add_shape("rect", "a", (0, 0, 10, 10))
            p.write(proj)
            r = subprocess.run(
                [sys.executable, "-c", self.PROBE.format(path=proj)],
                capture_output=True, text=True, cwd=str(REPO_ROOT))
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("CLEAN", r.stdout)

    def test_parse_shapes_is_module_level(self):
        # Item 13: the last headless->GUI dependency is gone; Project must not
        # reach into the window class to parse a project file.
        self.assertTrue(callable(areaDef._parse_shapes))
        self.assertFalse(hasattr(areaDef.AnnotatorWindow, "_parse_shapes"))


