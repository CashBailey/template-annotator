class TestDegradedDecoderBackends(unittest.TestCase):
    """Each optional decoder backend ALONE, the way a partial install runs.

    The loaders cache their module into a global (`_UNSET` until first use), and
    honour a value assigned from outside -- so forcing the real load first and
    then nulling the others leaves exactly one backend live.
    """

    _GLOBALS = ("_cv2", "_pyzbar", "_ZBarSymbol", "_AprilTagDetector")

    def setUp(self):
        from helpers.images import build_qr
        self.image = build_qr().convert("RGB")
        self._saved = {name: getattr(areaDef, name) for name in self._GLOBALS}
        areaDef._get_cv2()                    # resolve for real...
        areaDef._get_pyzbar()
        areaDef._get_apriltag_detector()
        areaDef._AprilTagDetector = None      # ...then keep only the one under test
        self.addCleanup(self._restore)

    def _restore(self):
        for name, value in self._saved.items():
            setattr(areaDef, name, value)

    def _assert_qr(self, dets):
        from helpers.images import QR_BBOX, QR_PAYLOAD
        self.assertEqual([d["payload"] for d in dets], [QR_PAYLOAD], dets)
        self.assertEqual(dets[0]["kind"], "qr")
        for got, want in zip(dets[0]["bbox"], QR_BBOX):
            self.assertAlmostEqual(got, want, delta=2.0, msg=f"{dets[0]['bbox']}")

    @unittest.skipUnless(HAS_CV2, "needs OpenCV")
    def test_markers_with_only_cv2(self):
        areaDef._pyzbar = None
        self._assert_qr(areaDef.detect_markers(self.image))

    @unittest.skipUnless(HAS_PYZBAR, "needs pyzbar + libzbar0")
    def test_markers_with_only_pyzbar(self):
        areaDef._cv2 = None
        self._assert_qr(areaDef.detect_markers(self.image))

    @unittest.skipUnless(HAS_PYZBAR, "needs pyzbar + libzbar0")
    def test_barcodes_with_only_pyzbar(self):
        from helpers.images import BARCODE_BBOX, BARCODE_PAYLOAD
        areaDef._cv2 = None
        dets = areaDef.detect_barcodes(self.image)
        self.assertEqual([d["payload"] for d in dets], [BARCODE_PAYLOAD], dets)
        self.assertEqual(dets[0]["kind"], "ean13")
        for got, want in zip(dets[0]["bbox"], BARCODE_BBOX):
            self.assertAlmostEqual(got, want, delta=2.0, msg=f"{dets[0]['bbox']}")

    @unittest.skipUnless(HAS_CV2, "needs OpenCV")
    def test_barcodes_with_only_cv2(self):
        from helpers.images import BARCODE_PAYLOAD
        areaDef._pyzbar = None
        # cv2.barcode exists in this build (OpenCV 4.13) but does not decode the
