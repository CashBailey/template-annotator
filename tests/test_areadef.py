class TestTextRegionSnapping(unittest.TestCase):
    """Text-region edges act as snap lines, and a field is clipped so it never
    shares area with a text region."""

    def test_text_boxes_to_lines(self):
        # Edges are Line records with no ink thickness: a text boundary is a
        # position, not a rule with a body to keep clear of.
        h, v = areaDef._text_boxes_to_lines([(100, 200, 180, 240)])
        self.assertIn(areaDef.Line(100, 200, 240), v)   # left edge
        self.assertIn(areaDef.Line(180, 200, 240), v)   # right edge
        self.assertIn(areaDef.Line(200, 100, 180), h)   # top edge
        self.assertIn(areaDef.Line(240, 100, 180), h)   # bottom edge
        self.assertEqual({line.half_thickness for line in h + v}, {0.0})

    def test_exclude_clips_left_edge(self):
        # Label occupies the field's left end -> field starts at the label's right.
        bbox, ch = areaDef._exclude_text_overlap(120, 205, 600, 238, [(100, 200, 180, 240)])
        self.assertTrue(ch)
        self.assertAlmostEqual(bbox[0], 180.0)
        self.assertEqual(bbox[1:], (205, 600, 238))

    def test_exclude_clips_right_edge(self):
        bbox, ch = areaDef._exclude_text_overlap(120, 205, 600, 238, [(560, 200, 650, 240)])
        self.assertTrue(ch)
        self.assertAlmostEqual(bbox[2], 560.0)

    def test_exclude_prefers_minimal_vertical_graze(self):
        # A field whose bottom dips a few px into a text box below is trimmed
        # vertically by that small amount, not clipped across its whole width.
        bbox, ch = areaDef._exclude_text_overlap(120, 205, 600, 240, [(300, 236, 500, 300)])
        self.assertTrue(ch)
        self.assertAlmostEqual(bbox[3], 236.0)
        self.assertEqual(bbox[0], 120)      # width preserved

    def test_exclude_leaves_unclippable_box(self):
        # Text spanning the whole field can't be clipped without destroying it.
        bbox, ch = areaDef._exclude_text_overlap(120, 205, 600, 250, [(100, 200, 700, 260)])
        self.assertFalse(ch)
        self.assertEqual(bbox, (120, 205, 600, 250))

    def test_combined_snaps_and_excludes(self):
        h_lines = [(240.0, 90.0, 620.0)]   # underline
        text = [(100, 205, 175, 238)]      # label on the left
        out, snapped = areaDef.snap_bbox_to_lines_and_text(
            118, 206, 600, 236, h_lines, [], text, tol=8, keep_size=False
        )
        self.assertTrue(snapped)
        self.assertGreaterEqual(out[0], 175.0)   # left clipped off the label
        ox = min(out[2], 175) - max(out[0], 100)
        oy = min(out[3], 238) - max(out[1], 205)
        self.assertFalse(ox > 0.5 and oy > 0.5)  # no shared area

    def test_keep_size_does_not_exclude(self):
        # While moving (keep_size), text edges still snap the box but it is never
        # resized/clipped, so its width and height are preserved exactly.
        out, _ = areaDef.snap_bbox_to_lines_and_text(
            120, 205, 600, 238, [], [], [(100, 200, 180, 240)], tol=8, keep_size=True
        )
        self.assertAlmostEqual(out[2] - out[0], 480.0)   # width unchanged
        self.assertAlmostEqual(out[3] - out[1], 33.0)    # height unchanged

    def test_project_snap_excludes_text(self):
        p = areaDef.Project("x", 800, 400, [])
        p.add_shape("rect", "f", (120, 205, 600, 238))
        n = p.snap_to_lines([], [], tol=8.0, text_boxes=[(100, 200, 180, 240)])
        self.assertEqual(n, 1)
        self.assertAlmostEqual(p.get(1).bbox()[0], 180.0)


